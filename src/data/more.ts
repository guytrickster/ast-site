/* поставляем ОЕМ-оригиналы: вычищаем служебные пометки «аналог», оставляя оригинальные каталожные номера */
const cleanName = (n: string): string =>
  n
    .replace(/, аналог АСТ\)/g, ")")
    .replace(/\s*\(аналог АСТ\)/g, "")
    .replace(/\s{2,}/g, " ")
    .trim();

const cleanTag = (s: string): string =>
  s.replace("Парковый аналог", "Оригинальные запчасти").replace(/аналог(а)? АСТ/g, "ОЕМ-оригинал");

const P = (sku: string, name: string, weight: number, status: Part["status"] = "in_stock"): Part => ({
  name: cleanName(name), sku, weight, status,
});

